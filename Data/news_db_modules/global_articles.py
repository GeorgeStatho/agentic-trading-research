from __future__ import annotations

from pathlib import Path
from typing import Any, Callable

from db_common import DB_PATH, get_connection
from .article_store import add_news_article
from .links import link_us_article, link_world_article


def _add_global_news_article(
    link_fn: Callable[..., int],
    *,
    source: str,
    article_key: str,
    title: str,
    source_url: str,
    source_page_url: str | None = None,
    summary: str | None = None,
    body: str | None = None,
    published_at: str | None = None,
    section: str | None = None,
    age_days: float | None = None,
    recency_score: float | None = None,
    source_reputation_score: float | None = None,
    directness_score: float | None = None,
    confirmation_score: float | None = None,
    independent_source_count: int | None = None,
    factuality_score: float | None = None,
    evidence_score: float | None = None,
    raw_json: Any | None = None,
    db_path: Path | str = DB_PATH,
    conn=None,
) -> int:
    if conn is None:
        with get_connection(db_path) as local_conn:
            return _add_global_news_article(
                link_fn,
                source=source,
                article_key=article_key,
                title=title,
                source_url=source_url,
                source_page_url=source_page_url,
                summary=summary,
                body=body,
                published_at=published_at,
                section=section,
                age_days=age_days,
                recency_score=recency_score,
                source_reputation_score=source_reputation_score,
                directness_score=directness_score,
                confirmation_score=confirmation_score,
                independent_source_count=independent_source_count,
                factuality_score=factuality_score,
                evidence_score=evidence_score,
                raw_json=raw_json,
                conn=local_conn,
            )

    article_id = add_news_article(
        source=source,
        article_key=article_key,
        title=title,
        source_url=source_url,
        summary=summary,
        body=body,
        published_at=published_at,
        section=section,
        age_days=age_days,
        recency_score=recency_score,
        source_reputation_score=source_reputation_score,
        directness_score=directness_score,
        confirmation_score=confirmation_score,
        independent_source_count=independent_source_count,
        factuality_score=factuality_score,
        evidence_score=evidence_score,
        raw_json=raw_json,
        conn=conn,
    )
    link_fn(article_id=article_id, source_page_url=source_page_url, conn=conn)
    return article_id


